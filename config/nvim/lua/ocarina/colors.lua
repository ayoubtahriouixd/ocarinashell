local M = {}

local function rgb(hex) return tonumber(hex:sub(2, 3), 16), tonumber(hex:sub(4, 5), 16), tonumber(hex:sub(6, 7), 16) end

--- a over b with alpha (0..1), like CSS color-mix(in srgb, a alpha, b)
local function mix(a, b, alpha)
  local r1, g1, b1 = rgb(a)
  local r2, g2, b2 = rgb(b)
  local function c(x, y) return math.floor(x * alpha + y * (1 - alpha) + 0.5) end
  return string.format("#%02x%02x%02x", c(r1, r2), c(g1, g2), c(b1, b2))
end
M.mix = mix

