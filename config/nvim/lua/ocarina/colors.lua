function M.apply()
  local p, from_file = require("ocarina.palette").load()
  if vim.g.colors_name then vim.cmd("hi clear") end
  vim.o.background = p.mode == "light" and "light" or "dark"
  vim.g.colors_name = "ocarina"
  for name, spec in pairs(M.groups(p)) do
    vim.api.nvim_set_hl(0, name, spec)
  end
  for i, col in ipairs(p.term) do
    vim.g["terminal_color_" .. (i - 1)] = col
  end
  M.palette, M.from_file = p, from_file
  vim.api.nvim_exec_autocmds("User", { pattern = "OcarinaTheme", modeline = false })
end

return M
