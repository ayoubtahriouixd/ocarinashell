def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fonts", default=os.environ.get("OCARINA_FONTS", "~/.local/share/fonts/ocarinashell").split(":")[0])
    ap.add_argument("--only", default="")
    ap.add_argument("--sheet", action="store_true")
    a = ap.parse_args()
    only = {int(x) for x in a.only.split(",") if x}
    (SRC / "img").mkdir(parents=True, exist_ok=True)
    (SRC / "tokens.css").write_text(tokens_css())
    if not (SRC / "img/oni-game.jpg").exists():
        game_scene(SRC / "img/oni-game.jpg")
    if not (SRC / "img/fluido-video.jpg").exists():
        video_scene(SRC / "img/fluido-video.jpg")
    fcss = font_css(a.fonts)
    from PIL import Image
    done = []
    with browser() as b:
        for n, (slug, title, fn, theme) in PAGES.items():
            if only and n not in only:
                continue
            html = (f'<!doctype html><html lang="es"><head><meta charset="utf-8"><title>{n:02d} · {title} — OcarinaShell</title>'
                    f'<link rel="stylesheet" href="tokens.css"><link rel="stylesheet" href="mock.css"></head>'
                    f'<body class="t-{theme}">{fn()}</body></html>\n')
            src = SRC / f"{n:02d}-{slug}.html"
            src.write_text(html)
            png = OUT / f"{n:02d}-{slug}.png"
            pg = b.new_page(viewport={"width": 1646, "height": 1029}, device_scale_factor=1.75)
            pg.goto(src.as_uri(), wait_until="load")
            if fcss:
                pg.add_style_tag(content=fcss)
            pg.evaluate("Promise.all([...document.fonts].map(f => f.load().catch(() => 0))).then(() => document.fonts.ready).then(() => true)")
            pg.wait_for_timeout(250)
            pg.screenshot(path=str(png), animations="disabled")
            pg.close()
            im = Image.open(png)
            if im.size != (2880, 1800):
                im.crop((0, 0, 2880, 1800)).save(png)
            done.append(png)
            print(f"{png.name:32s} 2880×1800")
    sheet_files = [f for f in (OUT / f"{n:02d}-{v[0]}.png" for n, v in PAGES.items()) if f.exists()]
    if a.sheet and sheet_files:                      # always every mockup, also with --only
        tw, th = 720, 450
        cols = 3
        rows = (len(sheet_files) + cols - 1) // cols
        sheet = Image.new("RGB", (cols * tw + (cols + 1) * 10, rows * th + (rows + 1) * 10), (30, 28, 32))
        for i, p in enumerate(sheet_files):
            sheet.paste(Image.open(p).convert("RGB").resize((tw, th), Image.LANCZOS), (10 + (i % cols) * (tw + 10), 10 + (i // cols) * (th + 10)))
        sheet.save(OUT / "contact-sheet.jpg", quality=88)
        print("contact-sheet.jpg")


if __name__ == "__main__":
    main()
