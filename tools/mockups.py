# ----------------------------------------------------------------------------- tokens.css from the theme JSON
def kebab(s):
    return "".join("-" + c.lower() if c.isupper() else c for c in s)


def tokens_css():
    out = ["/* GENERATED by tools/mockups.py from assets/data/themes/*.json — do not edit */"]
    for f in sorted((DATA / "themes").glob("*.json")):
        if f.name == "index.json":
            continue
        t = json.loads(f.read_text())
        v = {kebab(k): c for k, c in t["colors"].items()}
        tp = t["terminal"]
        v.update({"t-bg": tp["background"], "t-fg": tp["foreground"], "t-cursor": tp["cursor"], "t-sel": tp["selectionBackground"]})
        v.update({f"t{i}": c for i, c in enumerate(tp["palette"])})
        v.update({"glass-border": t["glass"]["border"], "glass-hl": t["glass"]["highlight"], "shadow": t["shadow"],
                  "scrim": t["scrim"], "ring-a": t["focusRing"]["active"][0], "ring-b": t["focusRing"]["active"][1],
                  "ring-off": t["focusRing"]["inactive"]})
        out.append(f".t-{t['id']} {{ " + " ".join(f"--{k}: {c};" for k, c in v.items()) + " }")
    return "\n".join(out) + "\n"


def font_css(font_dir):
    if not font_dir:
        return ""
    d = pathlib.Path(font_dir).expanduser()
    rules = []
    for fam, prefix, contains, wght in FONT_FACES:
        hits = [f for f in sorted(d.rglob(f"{prefix}*")) if f.suffix.lower() in (".ttf", ".otf") and contains in f.name]
        if hits:
            rules.append(f'@font-face {{ font-family: "{fam}"; src: url("{hits[0].as_uri()}"); font-weight: {wght}; font-display: block; }}')
    return "\n".join(rules)


