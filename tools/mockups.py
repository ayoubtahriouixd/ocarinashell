def game_scene(path):
    from PIL import Image, ImageDraw, ImageFilter
    import numpy as np
    W, H = 2880, 1800
    y = np.linspace(0, 1, H)[:, None]
    top, mid, low = np.array([24, 10, 38]), np.array([120, 24, 52]), np.array([255, 120, 64])
    sky = np.where(y < .55, top + (mid - top) * (y / .55), mid + (low - mid) * ((y - .55) / .45))
    img = np.repeat(sky[:, None, :], W, axis=1).astype(np.float32)
    yy, xx = np.mgrid[0:H, 0:W]
    d = np.hypot(xx - W * .62, yy - H * .6)
    img += (np.array([255, 90, 50]) * np.exp(-d / (H * .32))[..., None] * .55)
    img = np.where((d < H * .17)[..., None], np.array([255, 196, 120]) * (1 - .25 * (d / (H * .17)))[..., None] + 30, img)
    im = Image.fromarray(np.clip(img, 0, 255).astype(np.uint8), "RGB")
    dr = ImageDraw.Draw(im)
    rnd = random.Random(7)

    def ridge(base, amp, col, n=14):
        pts = [(0, H)]
        for i in range(n + 1):
            pts.append((W * i / n, base - amp * rnd.random() - (amp * .6 if i % 3 == 1 else 0)))
        pts.append((W, H))
        dr.polygon(pts, fill=col)
    ridge(H * .70, H * .14, (74, 22, 52))
    ridge(H * .78, H * .10, (44, 12, 34))
    # pagoda on the hill
    px, py = W * .80, H * .66
    for i in range(5):
        w = 150 - i * 22
        dr.polygon([(px - w, py - i * 70), (px + w, py - i * 70), (px + w * .7, py - i * 70 - 22), (px - w * .7, py - i * 70 - 22)], fill=(28, 8, 24))
        dr.rectangle((px - w * .45, py - i * 70 - 48, px + w * .45, py - i * 70 - 22), fill=(28, 8, 24))
    dr.line((px, py - 5 * 70 - 20, px, py - 5 * 70 - 120), fill=(28, 8, 24), width=8)
    # foreground cliff + swordsman silhouette
    dr.polygon([(0, H), (0, H * .78), (W * .18, H * .74), (W * .36, H * .8), (W * .44, H), ], fill=(12, 4, 10))
    sx, sy = W * .26, H * .74
    ink = (10, 3, 8)
    dr.polygon([(sx - 70, sy - 300), (sx + 70, sy - 300), (sx, sy - 350)], fill=ink)            # kasa hat
    dr.ellipse((sx - 26, sy - 300, sx + 26, sy - 250), fill=ink)
    dr.polygon([(sx - 40, sy - 252), (sx + 46, sy - 252), (sx + 70, sy - 40), (sx - 64, sy - 40)], fill=ink)
    dr.polygon([(sx - 40, sy - 240), (sx - 230, sy - 150), (sx - 260, sy - 120), (sx - 60, sy - 160)], fill=ink)   # cape
    dr.rectangle((sx - 44, sy - 40, sx - 14, sy + 6), fill=ink)
    dr.rectangle((sx + 16, sy - 40, sx + 46, sy + 6), fill=ink)
    glow = Image.new("RGB", (W, H))
    gd = ImageDraw.Draw(glow)
    gd.line((sx + 40, sy - 170, sx + 420, sy - 380), fill=(255, 40, 70), width=26)
    im = Image.fromarray(np.clip(np.asarray(im, np.float32) + np.asarray(glow.filter(ImageFilter.GaussianBlur(24)), np.float32) * .9, 0, 255).astype(np.uint8))
    dr = ImageDraw.Draw(im)
