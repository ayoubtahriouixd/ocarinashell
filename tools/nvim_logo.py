#!/usr/bin/env python3
"""Braille fallback of the ocarina for the Neovim dashboard (terminals without the kitty graphics protocol):

  config/nvim/lua/ocarina/logo.lua    `return { "⣠⣴…", … }` — 2×4 dots per cell, so the dots stay square

The source is the real mark (assets/logo/png/ocarinashell-mark-512.png). A dot is on where the mark is opaque and
not one of the dark finger holes (max channel: the 紅 body is dark in luma), so the holes read as holes.
ImageMagick does the resampling (stdlib otherwise).
usage: python3 tools/nvim_logo.py [--cols 28]
"""
import argparse
import pathlib
import subprocess
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
SRC = REPO / "assets/logo/png/ocarinashell-mark-512.png"
OUT = REPO / "config/nvim/lua/ocarina/logo.lua"
# braille dot bits by (x, y) inside the 2×4 cell
BITS = {(0, 0): 0x01, (0, 1): 0x02, (0, 2): 0x04, (1, 0): 0x08, (1, 1): 0x10, (1, 2): 0x20, (0, 3): 0x40, (1, 3): 0x80}


def pixels(w):
    """RGBA rows at w px wide (height keeps the aspect, rounded to a multiple of 4)."""
    size = subprocess.run(["magick", "identify", "-format", "%w %h", str(SRC)], capture_output=True, text=True,
                          check=True).stdout.split()
    sw, sh = int(size[0]), int(size[1])
    h = max(4, round(sh * w / sw / 4) * 4)
    raw = subprocess.run(["magick", str(SRC), "-resize", f"{w}x{h}!", "-depth", "8", "RGBA:-"], capture_output=True,
                         check=True).stdout
    return [[raw[(y * w + x) * 4:(y * w + x) * 4 + 4] for x in range(w)] for y in range(h)], h


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cols", type=int, default=28)
    args = ap.parse_args()
    w = args.cols * 2
    px, h = pixels(w)

    def on(x, y):
        r, g, b, a = px[y][x]
        return a > 140 and max(r, g, b) > 120

    lines = []
    for cy in range(h // 4):
        row = []
        for cx in range(args.cols):
            bits = 0
            for (dx, dy), bit in BITS.items():
                if on(cx * 2 + dx, cy * 4 + dy):
                    bits |= bit
            row.append(chr(0x2800 + bits))
        lines.append("".join(row).rstrip("⠀"))
    while lines and not lines[-1]:
        lines.pop()
    body = "\n".join(f'  "{line}",' for line in lines)
    OUT.write_text("-- GENERATED by tools/nvim_logo.py from assets/logo/png/ocarinashell-mark-512.png — do not edit.\n"
                   "-- Braille fallback of the dashboard ocarina (terminals without the kitty graphics protocol).\n"
                   f"return {{\n{body}\n}}\n", encoding="utf-8")
    print(f"{OUT.relative_to(REPO)}: {len(lines)} líneas × {args.cols} columnas")
    return 0


if __name__ == "__main__":
    sys.exit(main())
