def entries():
    out, seen = [], set()
    for f in sorted(PAGES.glob("*.qml")):
        page = FILES.get(f.stem)
        if not page:
            continue
        text = f.read_text(encoding="utf-8")
        for m in re.finditer(r'\btitle: "([^"\\]+)"', text):
            title = m.group(1)
            # the subtitle must belong to the same element: look ahead until the next title or element end
            nxt = text.find("title:", m.end())
            chunk = text[m.end(): nxt if nxt > 0 else len(text)][:600]
            sm = re.search(r'\bsub: "([^"\\]*)"', chunk)
            if (page, title) in seen:
                continue
            seen.add((page, title))
            e = {"p": page, "t": title}
            if sm:
                e["s"] = sm.group(1)
            if title in KEYS:
                e["k"] = KEYS[title]
            out.append(e)
    return out


def render():
    body = ",\n".join("    " + json.dumps(e, ensure_ascii=False) for e in entries())
    return (".pragma library\n// GENERATED by tools/settei_index.py from pages/*.qml — do not edit by hand.\n"
            "// Settei search index: p = page id, t = row title (exactly as in the page), s = subtitle, k = keywords.\n"
            "var entries = [\n" + body + "\n];\n")


if __name__ == "__main__":
    new = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == new
        print("índice de Settei al día" if ok else "índice de Settei desactualizado: tools/settei_index.py")
        sys.exit(0 if ok else 1)
    OUT.write_text(new, encoding="utf-8")
    print(f"{len(entries())} entradas → {OUT.relative_to(ROOT)}")
