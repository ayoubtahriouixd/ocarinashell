#!/usr/bin/env python3
"""Generates shell/modules/settei/index.js (the search index of Settei) from the pages: every row with a literal
`title: "…"` (SRow, ToggleRow, SliderRow, DropRow) becomes an entry with its literal `sub: "…"` if it has one.
  tools/settei_index.py           write the index
  tools/settei_index.py --check   exit 1 if the index is out of date (tests / CI)
"""
import json
